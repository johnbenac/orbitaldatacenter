import assert from 'node:assert/strict';
import {defaults,sizeDesign} from './dist/design.js';
import {createSimulation} from './dist/model.js';
import {selectedTerminal} from './dist/physics.js';
import {installedCommunications} from './dist/communications-packages.js';
import {buildEquipmentList} from './dist/equipment-list.js';
import {commissioningClock} from './dist/commissioning-clock.js';
import {DAY} from './dist/orbit.js';
const near=(a,b,tolerance=1e-7)=>assert.ok(Number.isFinite(a)&&Number.isFinite(b)&&Math.abs(a-b)<tolerance,`${a} != ${b}`);
const base={...defaults,missionYears:.003,duty:0,idleComputePolicy:'off',pumpStandbyPolicy:'follow',serviceRoute:'direct'};
const noRF=sizeDesign({...base,communicationsPackage:'optical-only',link:'optical'}),noRFSim=createSimulation(noRF);
assert.equal(installedCommunications(noRF).sBandInstalled,false);
assert.equal(selectedTerminal({...noRF.input,link:'auto'},0),'Optical');
const ready=commissioningClock(noRF).endS,contact=noRFSim.events(ready,DAY-ready).find(e=>e.type==='contact'&&e.end-Math.max(ready,e.start)>30);
assert.ok(contact,'A geometric contact is needed to test absent RF hardware.');
const contactStart=Math.max(ready,contact.start),t=contactStart+Math.min(60,(contact.end-contactStart)/2),s=noRFSim.at(t);
near(s.uplinkMbps,0);near(s.commandGoodputKbps,0);near(s.commandUploadedGB,0);near(s.hkDeliveredGB,0);
assert.ok(s.uplinkQueueMB+s.uplinkDroppedMB>0,'Offered commands remain visible as queued or dropped requests.');
assert.ok(s.hkStoredMB>0,'Local housekeeping recording is independent of its missing RF downlink.');
near(buildEquipmentList(noRF,s).rows.reduce((sum,r)=>sum+(r.instantPowerW||0),0)/1000,s.servedLoadKW,1e-6);
const noKa=sizeDesign({...base,communicationsPackage:'optical-ttc',link:'ka'}),noKaSim=createSimulation(noKa),k=noKaSim.at(t);
assert.equal(k.terminalInstalled,false);assert.match(k.unavailableReason,/not installed/);
assert.equal(k.acquired,false);near(k.linkCapacityMbps,0);near(k.goodputMbps,0);
assert.ok(k.commandUploadedGB>0,'Independent installed S-band remains available when the selected Ka payload terminal is absent.');
assert.ok(k.hkDeliveredGB>0);
near(buildEquipmentList(noKa,k).rows.reduce((sum,r)=>sum+(r.instantPowerW||0),0)/1000,k.servedLoadKW,1e-6);
console.log('Optional RF runtime: absent S-band has no lock or transfer, local recording and queued requests remain, absent Ka has no payload service, and independent S-band plus served-power ledgers remain valid.');
